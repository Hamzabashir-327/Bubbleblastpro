#!/usr/bin/env python3
"""Thins every level (fewer bubbles), then re-tunes it WITH the slow ceiling descent.

For each level it: truncates to a row cap, recomputes objectives, picks `drop_every`
(shots between ceiling drops; smaller = more pressure) as the strongest pressure the greedy bot
still beats >= 80% of the time, then sets shots / time / star scores from the bot results.
Resumable (writes tools/.retune_cache.json). Run:  python3 tools/retune_levels.py
"""
import glob
import json
import math
import os
import random
import statistics
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import board_sim as bs  # noqa: E402
import generate_levels as gl  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TRIALS = 8


def row_cap(lid):
    if lid % 10 == 0:
        return 7 + (lid // 10 - 1)       # boss: 7, 8, 9 rows
    if lid <= 3:
        return 4
    if lid <= 9:
        return 5
    if lid <= 19:
        return 6
    return 7


def thin(rows, cap, lid):
    rows = rows[:cap]
    rows = gl.strip_unsupported(rows)
    return rows


def play(rows, obj, cap, seed, drop):
    return [bs.bot_play(rows, obj, cap, random.Random(seed * 1000 + t), drop) for t in range(TRIALS)]


def main():
    cache_path = os.path.join(ROOT, "tools/.retune_cache.json")
    cache = json.load(open(cache_path)) if os.path.exists(cache_path) else {}
    report = ["# Level report (generated by tools/retune_levels.py)", "",
              "Bot: greedy, no power-ups, %d trials per check, WITH the ceiling descent. `drop` = shots between ceiling drops." % TRIALS, "",
              "| Lvl | Name | Rows | Bubbles | Colours | Objective | Shots | Drop every | Time | Median bot shots | Bot win rate | Stars (2/3) |",
              "|---:|---|---:|---:|---:|---|---:|---:|---:|---:|---:|---|"]
    for path in sorted(glob.glob(os.path.join(ROOT, "data/levels/level_*.json"))):
        d = json.load(open(path))
        lid = d["id"]
        if str(lid) in cache and d.get("drop_every", 0) > 0:
            report.append(cache[str(lid)])
            print("(kept)", cache[str(lid)], flush=True)
            continue
        rows = thin(d["rows"], row_cap(lid), lid)
        b = bs.Board()
        b.load_rows(rows)
        crit = b.count_kind(bs.RESCUE)
        otype = d["objective"]["type"]
        if otype == "rescue" and crit < 2:
            otype = "clear"
        seed = lid
        if otype == "rescue":
            obj = {"type": "rescue", "target": crit}
        elif otype == "score":
            probe = [r for r in play(rows, {"type": "clear"}, 80, seed, 0) if r["won"]]
            obj = {"type": "score", "target": int(round(0.7 * statistics.median([r["score"] for r in probe]) / 100.0)) * 100}
        else:
            obj = {"type": "clear"}
        base = [r for r in play(rows, obj, 80, seed + 5, 0) if r["won"]]
        shots_needed = sorted(r["shots"] for r in base)
        p90 = shots_needed[min(len(shots_needed) - 1, int(len(shots_needed) * 0.9))]
        cap = int(math.ceil(p90 * 1.3)) + 4
        chosen = None
        for drop in (5, 6, 7, 8, 9, 10):
            res = play(rows, obj, cap, seed + 11, drop)
            rate = sum(1 for r in res if r["won"]) / TRIALS
            if rate >= 0.8:
                chosen = (drop, res, rate)
                break
        if chosen is None:
            chosen = (12, play(rows, obj, cap, seed + 12, 12), 0)
            chosen = (12, chosen[1], sum(1 for r in chosen[1] if r["won"]) / TRIALS)
        drop, res, rate = chosen
        wins = [r for r in res if r["won"]] or base
        totals = [r["score"] + 50 * max(0, cap - r["shots"]) for r in wins]
        med = statistics.median(totals)
        time_limit = 0
        if d.get("time_limit", 0) > 0:
            time_limit = min(150, int(math.ceil((p90 * 6.0 + 25) / 5.0)) * 5)
        d.update({
            "rows": rows, "objective": obj, "shots": cap, "drop_every": drop, "time_limit": time_limit,
            "star_scores": [int(round(0.9 * med / 50.0)) * 50, int(round(1.3 * med / 50.0)) * 50],
        })
        json.dump(d, open(path, "w"), indent=1)
        line = "| %d | %s | %d | %d | %d | %s | %d | %d | %s | %.0f | %d%% | %d / %d |" % (
            lid, d["name"], len(rows), len(b.grid), d["colors"],
            obj["type"] + (" %d" % obj["target"] if "target" in obj else ""), cap, drop,
            ("%ds" % time_limit) if time_limit else "-", statistics.median(shots_needed), round(rate * 100),
            d["star_scores"][0], d["star_scores"][1])
        cache[str(lid)] = line
        json.dump(cache, open(cache_path, "w"))
        report.append(line)
        print(line, flush=True)
    open(os.path.join(ROOT, "docs/LEVEL_REPORT.md"), "w").write("\n".join(report) + "\n")


if __name__ == "__main__":
    main()
